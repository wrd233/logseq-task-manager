test('Agent records, explanation, explicit reconstruction and source attribution', async (t) => {
    const directory = await temporary(t), store = new HistoryStore(join(directory, 'history'));
    let cwd = directory;
    const service = new HistoryService({ store, workbench: { generations: new Map(), status: async () => ({ cwd }) } }), input = { requestId: 'first', title: 'Current work', nodes: [node('a', { sources: [{ kind: 'file', ref: 'a.md' }] })] };
    await writeFile(join(directory, 'a.md'), 'today');
    const a = await service.publish('s', input);
    assert.equal((await service.publish('s', input)).id, a.id);
    await service.explain('s', { snapshotId: a.id, requestId: 'why', text: 'Agent interpretation' });
    assert.equal((await service.read('s', a.id)).nodes[0].body, 'saved text');
    await assert.rejects(service.publish('s', { ...input, requestId: 'bad', origin: 'reconstructed' }), /RECONSTRUCTION_BASIS/);
    const past = await service.publish('s', { ...input, requestId: 'past', origin: 'reconstructed', occurredAt: '2020-01-01', reconstructedFrom: [a.id] });
    assert.equal(past.occurredAt, '2020-01-01T00:00:00.000Z');
    assert.ok(past.reconstructedAt > past.occurredAt);
    const list = await service.list('s', { track: 'default' });
    assert.equal(list.preferredId, a.id);
    assert.equal(list.records.find(r => r.id === a.id).explanations[0].text, 'Agent interpretation');
    const source = await service.source('s', { snapshotId: a.id, nodeId: 'a' });
    assert.equal(source.current.content, 'today');
    assert.match(source.notice, /未保存/);
    assert.match(quote({ snapshot: a, node: a.nodes[0], source }), /currentVersion/);
    cwd = join(directory, 'other');
    await mkdir(cwd);
    await assert.rejects(service.read('s', a.id), /ENOENT/);
});
test('Git checkpoints capture edits, untracked changes, commits, nested scope and credential exclusion', async (t) => {
    const root = await temporary(t);
    git(root, 'init');
    git(root, 'config', 'user.name', 'History Test');
    git(root, 'config', 'user.email', 'history@example.invalid');
    await mkdir(join(root, 'sub'));
    await writeFile(join(root, 'sub/a.md'), 'initial\n');
    await writeFile(join(root, '.ENV'), 'credential old');
    await writeFile(join(root, 'outside'), 'outside');
    git(root, 'add', '.');
    git(root, 'commit', '-m', 'initial');
    const store = new HistoryStore(join(root, 'history')), a = await store.append(root, await observeGit(join(root, 'sub')));
    await writeFile(join(root, 'sub/a.md'), 'edited\n');
    await writeFile(join(root, 'sub/new.md'), 'new one');
    await writeFile(join(root, '.ENV'), 'credential new');
    await writeFile(join(root, 'outside'), 'outside edited');
    const changed = await observeGit(join(root, 'sub'), a);
    assert.equal(changed.nodes.length, 2);
    assert.ok(changed.nodes.every(n => !n.title.startsWith('sub/')));
    assert.doesNotMatch(JSON.stringify(changed), /credential new|outside edited/);
    const b = await store.append(root, changed);
    assert.equal((await store.append(root, await observeGit(join(root, 'sub'), b))).id, b.id);
    await writeFile(join(root, 'sub/new.md'), 'new two');
    const c = await store.append(root, await observeGit(join(root, 'sub'), b));
    assert.notEqual(c.id, b.id);
    git(root, 'add', 'sub');
    git(root, 'commit', '-m', 'work changed');
    const commit = await store.append(root, await observeGit(join(root, 'sub'), c));
    assert.match(commit.facts.since, /edited/);
    assert.equal(commit.nodes.length, 2);
    assert.equal((await store.append(root, await observeGit(join(root, 'sub'), commit))).id, commit.id);
    assert.doesNotMatch(JSON.stringify(await observeGit(root)), /credential new/);
});
